create extension if not exists citext with schema extensions;

create schema if not exists private;
revoke all on schema private from public, anon, authenticated;
grant usage on schema private to authenticated, service_role;

create table public.tenants (
  id uuid primary key default gen_random_uuid(),
  name text not null check (char_length(name) between 2 and 120),
  slug text not null unique check (slug ~ '^[a-z0-9][a-z0-9-]{1,62}$'),
  status text not null default 'active' check (status in ('active', 'suspended', 'closed')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.tenant_members (
  id uuid primary key default gen_random_uuid(),
  tenant_id uuid not null references public.tenants(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null default 'sales' check (role in ('owner', 'admin', 'manager', 'sales', 'viewer')),
  created_at timestamptz not null default now(),
  unique (tenant_id, user_id)
);

create table public.sites (
  id uuid primary key default gen_random_uuid(),
  tenant_id uuid not null references public.tenants(id) on delete cascade,
  public_id uuid not null default gen_random_uuid() unique,
  name text not null check (char_length(name) between 2 and 120),
  base_url text not null,
  allowed_origins text[] not null default '{}',
  status text not null default 'active' check (status in ('active', 'paused', 'revoked')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (tenant_id, base_url)
);

create table private.site_credentials (
  site_id uuid primary key references public.sites(id) on delete cascade,
  write_token_hash text not null,
  rotated_at timestamptz not null default now()
);

create table public.contacts (
  id uuid primary key default gen_random_uuid(),
  tenant_id uuid not null references public.tenants(id) on delete cascade,
  site_id uuid references public.sites(id) on delete set null,
  email extensions.citext not null,
  first_name text not null default '',
  last_name text not null default '',
  phone text not null default '',
  company text not null default '',
  status text not null default 'new' check (status in ('new', 'contacted', 'qualified', 'customer', 'lost')),
  source text not null default 'website',
  owner_user_id uuid references auth.users(id) on delete set null,
  marketing_consent boolean not null default false,
  consent_recorded_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (tenant_id, email)
);

create table public.visitors (
  id uuid primary key default gen_random_uuid(),
  tenant_id uuid not null references public.tenants(id) on delete cascade,
  site_id uuid not null references public.sites(id) on delete cascade,
  visitor_uuid uuid not null,
  contact_id uuid references public.contacts(id) on delete set null,
  first_seen timestamptz not null default now(),
  last_seen timestamptz not null default now(),
  first_landing_url text,
  first_referrer text,
  locale text not null default '',
  device_type text not null default '',
  sessions_count integer not null default 0 check (sessions_count >= 0),
  pageviews_count integer not null default 0 check (pageviews_count >= 0),
  engagement_score integer not null default 0 check (engagement_score between 0 and 100),
  unique (site_id, visitor_uuid)
);

create table public.sessions (
  id uuid primary key default gen_random_uuid(),
  tenant_id uuid not null references public.tenants(id) on delete cascade,
  site_id uuid not null references public.sites(id) on delete cascade,
  visitor_id uuid not null references public.visitors(id) on delete cascade,
  session_uuid uuid not null,
  started_at timestamptz not null default now(),
  last_activity_at timestamptz not null default now(),
  landing_url text,
  referrer text,
  utm_source text not null default '',
  utm_medium text not null default '',
  utm_campaign text not null default '',
  unique (site_id, session_uuid)
);

create table public.events (
  id bigint generated by default as identity primary key,
  tenant_id uuid not null references public.tenants(id) on delete cascade,
  site_id uuid not null references public.sites(id) on delete cascade,
  visitor_id uuid not null references public.visitors(id) on delete cascade,
  session_id uuid not null references public.sessions(id) on delete cascade,
  request_id uuid not null,
  event_type text not null check (event_type in ('page_view', 'click', 'scroll', 'heartbeat', 'form_started', 'form_submitted', 'download', 'voice_intent')),
  page_url text,
  page_title text not null default '',
  element_name text not null default '',
  event_data jsonb not null default '{}'::jsonb,
  occurred_at timestamptz not null default now(),
  unique (site_id, request_id)
);

create table public.activities (
  id bigint generated by default as identity primary key,
  tenant_id uuid not null references public.tenants(id) on delete cascade,
  site_id uuid references public.sites(id) on delete set null,
  contact_id uuid references public.contacts(id) on delete cascade,
  visitor_id uuid references public.visitors(id) on delete set null,
  activity_type text not null,
  subject text not null default '',
  body text,
