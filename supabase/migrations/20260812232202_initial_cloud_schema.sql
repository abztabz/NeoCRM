create or replace function private.is_tenant_member(p_tenant_id uuid)
returns boolean
language sql
security definer
stable
set search_path = ''
as $$
  select exists (
    select 1
    from public.tenant_members tm
    where tm.tenant_id = p_tenant_id
      and tm.user_id = (select auth.uid())
  );
$$;

create or replace function private.has_tenant_role(p_tenant_id uuid, p_roles text[])
returns boolean
language sql
security definer
stable
set search_path = ''
as $$
  select exists (
    select 1
    from public.tenant_members tm
    where tm.tenant_id = p_tenant_id
      and tm.user_id = (select auth.uid())
      and tm.role = any (p_roles)
  );
$$;

revoke all on function private.is_tenant_member(uuid) from public, anon;
revoke all on function private.has_tenant_role(uuid, text[]) from public, anon;
grant execute on function private.is_tenant_member(uuid) to authenticated;
grant execute on function private.has_tenant_role(uuid, text[]) to authenticated;

create or replace function public.verify_site_token(p_site_public_id uuid, p_token_hash text)
returns table (
  site_id uuid,
  tenant_id uuid,
  base_url text,
  allowed_origins text[]
)
language sql
security definer
stable
set search_path = ''
as $$
  select s.id, s.tenant_id, s.base_url, s.allowed_origins
  from public.sites s
  join private.site_credentials sc on sc.site_id = s.id
  join public.tenants t on t.id = s.tenant_id
  where s.public_id = p_site_public_id
    and sc.write_token_hash = p_token_hash
    and s.status = 'active'
    and t.status = 'active'
  limit 1;
$$;

revoke all on function public.verify_site_token(uuid, text) from public, anon, authenticated;
grant execute on function public.verify_site_token(uuid, text) to service_role;

